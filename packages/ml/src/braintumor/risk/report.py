"""Plain-language surgical risk report generation.

Default behaviour is a template-based report — no external API key or
network call required, so the project runs end-to-end out of the box.

If you later want an LLM-polished version of the same report, set the
ANTHROPIC_API_KEY environment variable; ``build_report_text`` will use it
automatically. Every LLM report is machine-checked before it is used: any
number that is not in the structured data, any missing disclaimer, or any
clinical-recommendation wording makes it fall back to the template.
"""

from __future__ import annotations

import os
import re

from braintumor.risk.mapping import (
    NO_TUMOR_TIER,
    NOT_APPLICABLE_RISK,
    RiskRegion,
    TumorDetectionStatus,
)

DISCLAIMER = (
    "This report is generated by a research/educational prototype. Region "
    "metrics are a Harvard-Oxford atlas-based, registration-dependent estimate. "
    "This is NOT a medical device and must NOT be used for real surgical "
    "planning or clinical decisions. Always consult a qualified radiologist "
    "or neurosurgeon."
)

CLINICAL_DISCLAIMER = (
    "A model's negative prediction is not proof that a patient has no tumor. "
    "This is NOT a clinical clearance. The model can miss tumors "
    "(especially small, atypical or low-contrast ones) and has not been "
    "validated for clinical use. Review the images and the segmentation "
    "overlay manually."
)

REGISTRATION_UNCERTAINTY_FOOTNOTE = (
    "Footnote: Region boundaries are derived from the Harvard-Oxford atlas at a 25% "
    "probability threshold. Overlaps below 50 voxels (~50 mm³) or distances within "
    "3.0 mm fall within spatial registration and atlas uncertainty margins and represent "
    "marginal contact rather than confirmed tissue invasion."
)

_TIER_ORDER = ("High", "Moderate", "Low")

# Wording an LLM must not use (heuristic check, case-insensitive).
_FORBIDDEN_PATTERNS = (
    r"recommend",
    r"should undergo",
    r"resect",
    r"safe to operate",
    r"\bno risk\b(?!\s+tier)",
    r"risk-free",
    r"guarantee",
)

_NUMBER_RE = re.compile(r"\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+(?:\.\d+)?")


def _is_no_tumor(regions: list[RiskRegion], tumor_volume_mm3: float | None = None) -> bool:
    if any(
        getattr(r, "mapping_status", "") in ("FAILED_REGISTRATION", "INVALID_SEGMENTATION")
        or getattr(r, "registration_quality", "") == "FAILED"
        for r in regions
    ):
        return False
    if tumor_volume_mm3 is not None and tumor_volume_mm3 <= 0:
        return True
    return bool(regions) and all(
        getattr(r, "tumor_detection_status", "") == TumorDetectionStatus.NO_TUMOR_DETECTED.value
        or (
            r.risk_tier in (NO_TUMOR_TIER, NOT_APPLICABLE_RISK, "No tumor detected")
            and getattr(r, "mapping_status", "") not in ("FAILED_REGISTRATION", "INVALID_SEGMENTATION")
            and getattr(r, "registration_quality", "") != "FAILED"
        )
        for r in regions
    )


def _no_tumor_report(case_name: str) -> str:
    return "\n".join(
        [
            f"Experimental Region Proximity Analysis Report — {case_name}",
            "",
            "Tumor Detection Status: NO_TUMOR_DETECTED",
            "Status: NO TUMOR DETECTED — No tumor detected by the model in this volume.",
            "Whole tumor volume: 0 mm^3",
            "Eloquent brain structure risk: NOT_APPLICABLE.",
            "No functional-region overlap or distance was assessed, and no risk tiers were assigned.",
            "",
            f"Clinical Disclaimer: {CLINICAL_DISCLAIMER}",
            "",
            DISCLAIMER,
        ]
    )


def _fmt_distance(distance_mm: float | None) -> str:
    return "n/a" if distance_mm is None else f"{distance_mm} mm"


def _failed_registration_report(case_name: str, reason: str | None = None) -> str:
    lines = [
        f"Experimental Region Proximity Analysis Report — {case_name}",
        "",
        "Status: ANATOMICAL MAPPING FAILED — Atlas registration or affine transform error.",
        "Registration between the patient scan and the atlas could not be computed.",
    ]
    if reason:
        lines.append(f"Reason: {reason}")
    lines.extend(
        [
            "To prevent false reassurance, no risk tiers were assigned, and regions were not given a minimal score.",
            "",
            "Manual neuroradiological inspection and dedicated clinical image registration are required.",
            "",
            DISCLAIMER,
        ]
    )
    return "\n".join(lines)


def _invalid_segmentation_report(case_name: str) -> str:
    return "\n".join(
        [
            f"Experimental Region Proximity Analysis Report — {case_name}",
            "",
            "Status: INVALID SEGMENTATION INPUT — Mask contains invalid labels or non-finite values.",
            "Anatomical risk mapping cannot proceed with an invalid segmentation input.",
            "No risk tiers were assigned.",
            "",
            DISCLAIMER,
        ]
    )


def _template_report(case_name: str, regions: list[RiskRegion], tumor_volume_mm3: float | None) -> str:
    if any(
        getattr(r, "mapping_status", "") == "FAILED_REGISTRATION"
        or getattr(r, "registration_quality", "") == "FAILED"
        for r in regions
    ):
        reason = next((getattr(r, "mapping_reason", None) for r in regions if getattr(r, "mapping_reason", None)), None)
        return _failed_registration_report(case_name, reason=reason)

    if any(getattr(r, "mapping_status", "") == "INVALID_SEGMENTATION" for r in regions):
        return _invalid_segmentation_report(case_name)

    if _is_no_tumor(regions, tumor_volume_mm3):
        return _no_tumor_report(case_name)

    lines = [
        f"Experimental Region Proximity Analysis Report — {case_name}",
        "",
        "Tumor Detection Status: TUMOR_DETECTED",
        "Status: Tumor detected by the model.",
        "",
    ]

    if tumor_volume_mm3 is not None:
        lines.append(f"Whole tumor volume: {tumor_volume_mm3:,.0f} mm^3")
        lines.append("")

    counts = {t: sum(1 for r in regions if r.risk_tier == t) for t in _TIER_ORDER}
    lines.append(
        f"Harvard-Oxford atlas-based, registration-dependent estimate across {len(regions)} regions: "
        f"{counts['High']} High, {counts['Moderate']} Moderate, {counts['Low']} Low."
    )
    lines.append("")

    lines.append("Region findings:")
    for tier in _TIER_ORDER:
        for r in regions:
            if r.risk_tier == tier:
                vox_count = getattr(r, "overlap_voxels", 0)
                vox_unit = "voxel" if vox_count == 1 else "voxels"
                vox_desc = f" ({vox_count} {vox_unit})" if vox_count > 0 else ""
                contact_desc = f", contact: {r.contact_label}" if getattr(r, "contact_label", None) and r.contact_label not in ("none", "Not applicable") else ""

                if getattr(r, "contact_type", "") == "marginal_contact":
                    loc_desc = "contact (within uncertainty)"
                elif getattr(r, "contact_type", "") == "within_registration_uncertainty":
                    loc_desc = f"distance within registration uncertainty (<= 3.0 mm){contact_desc}"
                else:
                    loc_desc = f"distance {_fmt_distance(r.distance_mm)}{contact_desc}"

                lines.append(
                    f"- {r.region}: {tier}; overlap {r.overlap_pct}% of tumor{vox_desc}, {loc_desc}"
                )
    lines.append("")

    lines.append(
        "Summary: this experimental analysis estimates overlap and proximity "
        "using the Harvard-Oxford atlas in standard MNI152 space. These estimates do not establish "
        "actual anatomical involvement, neurological deficits, or surgical risk."
    )

    lines.append("")
    lines.append(REGISTRATION_UNCERTAINTY_FOOTNOTE)
    lines.append("")
    lines.append(DISCLAIMER)
    return "\n".join(lines)


# --------------------------------------------------------------------------
# Verification of generated text
# --------------------------------------------------------------------------

def _numbers_in(text: str, case_name: str) -> list[float]:
    cleaned = (
        text.replace(DISCLAIMER, " ")
        .replace(CLINICAL_DISCLAIMER, " ")
        .replace(REGISTRATION_UNCERTAINTY_FOOTNOTE, " ")
        .replace(case_name, " ")
    )
    cleaned = re.sub(r"mm\^3|mm³|mm3", "mm", cleaned)
    cleaned = re.sub(r"MNI-?152", "MNI", cleaned, flags=re.IGNORECASE)
    return [float(m.replace(",", "")) for m in _NUMBER_RE.findall(cleaned)]


def _allowed_numbers(
    case_name: str,
    regions: list[RiskRegion],
    tumor_volume_mm3: float | None,
) -> set[float]:
    allowed: set[float] = {0.0}

    def add(value: float | None) -> None:
        if value is not None:
            allowed.add(round(float(value), 6))

    for r in regions:
        add(r.overlap_pct)
        add(r.distance_mm)
        add(r.region_overlap_pct)
        add(r.overlap_volume_mm3)
        add(r.region_volume_mm3)
        add(r.tumor_volume_mm3)
        add(getattr(r, "overlap_voxels", 0))
        if r.overlap_volume_mm3:
            add(round(r.overlap_volume_mm3))
        if r.region_volume_mm3:
            add(round(r.region_volume_mm3))

    # Add margin numbers from footnote (25% threshold, 50 voxels/mm³, 3.0 mm uncertainty)
    add(25.0)
    add(50.0)
    add(3.0)

    if tumor_volume_mm3 is not None:
        add(tumor_volume_mm3)
        add(round(tumor_volume_mm3))
        add(round(tumor_volume_mm3, 1))

    add(len(regions))
    for tier in _TIER_ORDER:
        add(sum(1 for r in regions if r.risk_tier == tier))

    for match in _NUMBER_RE.findall(case_name):
        add(float(match.replace(",", "")))

    return allowed


def verify_report_numbers(
    text: str,
    case_name: str,
    regions: list[RiskRegion],
    tumor_volume_mm3: float | None,
) -> list[str]:
    """Return a list of problems found in a report (empty list = passes).

    Checks that
      * every number in the text appears in the structured data,
      * the exact disclaimer is present,
      * no clinical-recommendation wording is used.
    """
    problems: list[str] = []

    allowed = _allowed_numbers(case_name, regions, tumor_volume_mm3)
    for number in _numbers_in(text, case_name):
        if round(number, 6) not in allowed:
            problems.append(f"number not in data: {number:g}")

    if DISCLAIMER not in text:
        problems.append("exact disclaimer missing")

    lowered = text.replace(DISCLAIMER, " ").lower()
    for pattern in _FORBIDDEN_PATTERNS:
        if re.search(pattern, lowered):
            problems.append(f"forbidden wording: '{pattern}'")

    for r in regions:
        for other_tier in _TIER_ORDER:
            if other_tier != r.risk_tier and r.risk_tier in _TIER_ORDER:
                pattern = rf"\b{re.escape(r.region)}\b[^\n\.\;]*?\b{other_tier}\b"
                if re.search(pattern, text, re.IGNORECASE):
                    problems.append(
                        f"contradictory risk tier for {r.region}: mentioned {other_tier}, expected {r.risk_tier}"
                    )

    return problems


