# Optional LLM report
# --------------------------------------------------------------------------

def _llm_generate(case_name: str, regions: list[RiskRegion], tumor_volume_mm3: float | None) -> str | None:
    """Raw LLM text (unverified). None if no key is set or the call fails."""
    api_key = os.getenv("ANTHROPIC_API_KEY")
    if not api_key:
        return None

    try:
        import anthropic

        client = anthropic.Anthropic(api_key=api_key)
        def _vox_str(count: int) -> str:
            return f"{count} voxel" if count == 1 else f"{count} voxels"

        region_lines = "\n".join(
            f"- {r.region}: overlap={r.overlap_pct}% ({_vox_str(getattr(r, 'overlap_voxels', 0))}), "
            f"distance_mm={r.distance_mm}, contact={getattr(r, 'contact_label', 'none')}, "
            f"risk={r.risk_tier}, function={r.function}"
            for r in regions
        )
        prompt = (
            f"Write a short (under 250 words), plain-English experimental region-overlap "
            f"summary for case '{case_name}' based on this structured data. "
            f"Use the numbers exactly as given: do not round, convert units, or add "
            f"any other numbers. Show overlap voxels and contact labels (such as marginal contact or within registration uncertainty). "
            f"Do not invent numbers or make clinical or surgical recommendations. "
            f"Explain that metrics are a Harvard-Oxford atlas-based, registration-dependent estimate. "
            f"Include this exact footnote: \"{REGISTRATION_UNCERTAINTY_FOOTNOTE}\"\n"
            f"End with this exact disclaimer on its own line: \"{DISCLAIMER}\"\n\n"
            f"Tumor volume: {tumor_volume_mm3} mm^3\n"
            f"Regions:\n{region_lines}"
        )
        response = client.messages.create(
            model="claude-sonnet-4-6",
            max_tokens=500,
            messages=[{"role": "user", "content": prompt}],
        )
        return "".join(b.text for b in response.content if hasattr(b, "text")).strip()
    except Exception:
        return None


def _llm_report(case_name: str, regions: list[RiskRegion], tumor_volume_mm3: float | None) -> str | None:
    """Optional: LLM-written version of the same facts, verified before use.

    Returns None (caller falls back to the template) if no API key is
    configured, the call fails, or the text fails verification.
    """
    text = _llm_generate(case_name, regions, tumor_volume_mm3)
    if not text:
        return None
    if verify_report_numbers(text, case_name, regions, tumor_volume_mm3):
        return None
    return text


def build_report_text(
    case_name: str,
    regions: list[RiskRegion],
    tumor_volume_mm3: float | None = None,
) -> str:
    """Build the final report text.

    * Registration failed -> explicit registration failure report.
    * Invalid segmentation -> explicit invalid segmentation report.
    * No tumor detected -> fixed "no tumor detected" text (no LLM, no tiers).
    * Otherwise -> verified LLM version if configured, else the template.
    """
    if any(
        getattr(r, "mapping_status", "") == "FAILED_REGISTRATION"
        or getattr(r, "registration_quality", "") == "FAILED"
        for r in regions
    ):
        reason = next((getattr(r, "mapping_reason", None) for r in regions if getattr(r, "mapping_reason", None)), None)
        return _failed_registration_report(case_name, reason=reason)

    if any(getattr(r, "mapping_status", "") == "INVALID_SEGMENTATION" for r in regions):
        return _invalid_segmentation_report(case_name)

    if _is_no_tumor(regions, tumor_volume_mm3):
        return _no_tumor_report(case_name)

    llm_text = _llm_report(case_name, regions, tumor_volume_mm3)
    return llm_text if llm_text else _template_report(case_name, regions, tumor_volume_mm3)